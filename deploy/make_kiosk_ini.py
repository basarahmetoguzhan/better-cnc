#!/usr/bin/env python3
"""Derive a machine's kiosk INI from its INI: only [DISPLAY]DISPLAY changes.

    python3 deploy/make_kiosk_ini.py configs/test-rig/test-rig.ini
    -> writes configs/test-rig/test-rig-kiosk.ini and prints its path

The kiosk INI is written NEXT TO its source, so every relative path in it
(HALFILE, PARAMETER_FILE, TOOL_TABLE, PROGRAM_PREFIX) resolves exactly as when
the same machine runs under axis: same HAL, same parameter file, same tool
table. The one difference is the display program, deploy/bettercnc-display,
which starts the operator UI. scripts/ini_derive.py does the copying and
refuses if [DISPLAY]DISPLAY is not found exactly once.

deploy/kiosk-session rewrites it on every LinuxCNC start, so an edit to the
source INI reaches the kiosk on the next start; it is gitignored
(*-kiosk.ini).
"""

import os
import sys

DEPLOY_DIR = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(DEPLOY_DIR)
DISPLAY_PROGRAM = os.path.join(DEPLOY_DIR, "bettercnc-display")

sys.path.insert(0, os.path.join(REPO, "scripts"))
from ini_derive import derive  # noqa: E402


def kiosk_path(source: str) -> str:
    stem, _ = os.path.splitext(os.path.abspath(source))
    return stem + "-kiosk.ini"


def convert(text: str, source: str) -> str:
    return derive(
        text,
        {("DISPLAY", "DISPLAY"): DISPLAY_PROGRAM},
        source,
        append=(
            "\n# Generated by deploy/make_kiosk_ini.py from {} - do not edit, it is\n"
            "# rewritten on every kiosk start. Only [DISPLAY]DISPLAY differs.\n".format(
                os.path.basename(source)
            )
        ),
    )


def main(argv) -> int:
    if len(argv) != 2:
        sys.stderr.write("usage: make_kiosk_ini.py MACHINE.ini\n")
        return 2
    source = argv[1]
    if source.endswith("-kiosk.ini"):
        sys.stderr.write("make_kiosk_ini: {} is already a kiosk INI\n".format(source))
        return 2
    try:
        with open(source, "r", encoding="utf-8") as fh:
            text = fh.read()
    except OSError as exc:
        # One line for the kiosk's boot screen, not a traceback.
        sys.stderr.write("{} okunamadı: {}\n".format(source, exc.strerror or exc))
        return 1
    out = kiosk_path(source)
    tmp = out + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(convert(text, source))
    os.replace(tmp, out)
    print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
